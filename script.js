// ==================== Typing Animation ====================
const typingText = document.querySelector('.typing-text');
const phrases = [
    'Creative Designer',
    'Front-End Developer',
    'UI/UX Specialist',
    'Digital Storyteller',
    'Brand Strategist'
];

let phraseIndex = 0;
let charIndex = 0;
let isDeleting = false;
let typingSpeed = 100;

function typeEffect() {
    const currentPhrase = phrases[phraseIndex];

    if (isDeleting) {
        typingText.textContent = currentPhrase.substring(0, charIndex - 1);
        charIndex--;
        typingSpeed = 50;
    } else {
        typingText.textContent = currentPhrase.substring(0, charIndex + 1);
        charIndex++;
        typingSpeed = 100;
    }

    if (!isDeleting && charIndex === currentPhrase.length) {
        // Pause at end of phrase
        typingSpeed = 2000;
        isDeleting = true;
    } else if (isDeleting && charIndex === 0) {
        isDeleting = false;
        phraseIndex = (phraseIndex + 1) % phrases.length;
        typingSpeed = 500;
    }

    setTimeout(typeEffect, typingSpeed);
}

// Start typing animation
typeEffect();

// ==================== Portfolio Filter ====================
const filterBtns = document.querySelectorAll('.filter-btn');
const portfolioItems = document.querySelectorAll('.portfolio-item');

filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
        // Remove active class from all buttons
        filterBtns.forEach(b => b.classList.remove('active'));
        // Add active class to clicked button
        btn.classList.add('active');

        const filter = btn.getAttribute('data-filter');

        portfolioItems.forEach(item => {
            const category = item.getAttribute('data-category');

            if (filter === 'all' || category === filter) {
                item.style.display = 'block';
                setTimeout(() => {
                    item.style.opacity = '1';
                    item.style.transform = 'scale(1)';
                }, 10);
            } else {
                item.style.opacity = '0';
                item.style.transform = 'scale(0.8)';
                setTimeout(() => {
                    item.style.display = 'none';
                }, 300);
            }
        });
    });
});

// ==================== Scroll Reveal Animation ====================
const scrollRevealElements = document.querySelectorAll('.about, .skills, .portfolio, .experience, .contact');

const elementInView = (el, offset = 100) => {
    const elementTop = el.getBoundingClientRect().top;
    return elementTop <= (window.innerHeight || document.documentElement.clientHeight) - offset;
};

const displayScrollElement = (element) => {
    element.classList.add('scroll-reveal', 'active');
};

const hideScrollElement = (element) => {
    element.classList.remove('active');
};

const handleScrollAnimation = () => {
    scrollRevealElements.forEach((el) => {
        if (elementInView(el, 150)) {
            displayScrollElement(el);
        }
    });
};

window.addEventListener('scroll', handleScrollAnimation);
handleScrollAnimation(); // Check on page load

// ==================== Skill Progress Animation ====================
const skillBars = document.querySelectorAll('.skill-progress');

const animateSkillBars = () => {
    skillBars.forEach(bar => {
        const barTop = bar.getBoundingClientRect().top;
        const triggerBottom = window.innerHeight / 5 * 4;

        if (barTop < triggerBottom) {
            const width = bar.style.width;
            bar.style.width = '0';
            setTimeout(() => {
                bar.style.width = width;
            }, 100);
        }
    });
};

let skillsAnimated = false;
const skillsSection = document.querySelector('.skills');

const checkSkillsInView = () => {
    if (skillsAnimated) return;

    const skillsTop = skillsSection.getBoundingClientRect().top;
    const triggerBottom = window.innerHeight / 5 * 4;

    if (skillsTop < triggerBottom) {
        animateSkillBars();
        skillsAnimated = true;
    }
};

window.addEventListener('scroll', checkSkillsInView);

// ==================== Stats Counter Animation ====================
const statCards = document.querySelectorAll('.stat-card h3');

const animateCounter = (element, target) => {
    const increment = target / 100;
    let current = 0;
    const updateCounter = () => {
        current += increment;
        if (current < target) {
            element.textContent = Math.ceil(current) + '+';
            requestAnimationFrame(updateCounter);
        } else {
            element.textContent = target + '+';
        }
    };
    updateCounter();
};

let statsAnimated = false;
const aboutSection = document.querySelector('.about');

const checkStatsInView = () => {
    if (statsAnimated) return;

    const aboutTop = aboutSection.getBoundingClientRect().top;
    const triggerBottom = window.innerHeight / 5 * 4;

    if (aboutTop < triggerBottom) {
        statCards.forEach(stat => {
            const target = parseInt(stat.textContent);
            animateCounter(stat, target);
        });
        statsAnimated = true;
    }
};

window.addEventListener('scroll', checkStatsInView);

